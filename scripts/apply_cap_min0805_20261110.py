#!/usr/bin/env python3
"""VoiceMemory v1: replace only formerly 0603 capacitors with KiCad 10 native 1206.

The source geometry (silk, fab, courtyard, pads and 3D model) is imported
unchanged from the existing canonical KiCad C_1206_3216Metric footprint C1
embedded in this same project; NO custom symbol or compact cache is generated.
Keep instance position, ref/value label positions, pin numbers, pin net and UUIDs.
The CAD application's ERC/DRC and copper refill are not run by this script.
"""
import re, json, uuid, hashlib
from pathlib import Path
BASE=Path(__file__).resolve().parents[1]
P=BASE/'hardware/kicad/voicememory'
SCH=P/'voicememory.kicad_sch'
PCB=P/'voicememory.kicad_pcb'
TARGETS={
  **{f'C{n}': ('1uF/25V PMLCAP', 'Akizuki 107397 25MU105MA23216 25V 1uF PMLCAP') for n in (2,4,11,19)},
  **{f'C{n}': ('0.1uF/100V CH', 'Sengoku GRM31C2C2A104JA01L 100V 0.1uF CH (JIS)') for n in (7,8,10,14,15,16,17)},
}

def balanced(s,start):
    assert s[start]=='('
    q=False; slash=False; depth=0
    for i in range(start,len(s)):
        c=s[i]
        if q:
            if slash:slash=False
            elif c=='\\':slash=True
            elif c=='"':q=False
        elif c=='"':q=True
        elif c=='(':depth+=1
        elif c==')':
            depth-=1
            if depth==0:return i+1
    raise RuntimeError('unbalanced expression')

def top(s,typ):
    return [(m.start()+1,balanced(s,m.start()+1)) for m in re.finditer(r'^\t\('+re.escape(typ)+r'\s',s,re.M)]

def instance(s,typ,ref):
    hits=[]
    for a,b in top(s,typ):
        if re.search(r'\(property "Reference" "'+re.escape(ref)+r'"',s[a:b]):hits.append((a,b))
    if len(hits)!=1:raise ValueError((typ,ref,len(hits)))
    return hits[0]

def sub1(s,old,new,tag):
    if s.count(old)!=1:raise ValueError((tag,'not uniquely present',old,s.count(old)))
    return s.replace(old,new,1)

def block_by_header(s, header):
    matches=list(re.finditer('\\n\\t\\t'+re.escape(header),s))
    if len(matches)!=1:raise ValueError((header,len(matches)))
    i=matches[0].start()+len('\n\t\t')
    return s[i:balanced(s,i)]

def native_1206_geometry(template):
    i=template.index('\n\t\t(fp_line')+1
    j=template.index('\n\t\t(pad "1"')+1
    return template[i:j]

def replacing_pad_geom(block, template_pad, ref):
    geom = re.search(r'\(at [^)]*\)\s*\(size [^)]*\)\s*\(layers [^)]*\)\s*\(roundrect_rratio [^)]*\)',template_pad,re.S)
    old  = re.search(r'\(at [^)]*\)\s*\(size [^)]*\)\s*\(layers [^)]*\)\s*\(roundrect_rratio [^)]*\)',block,re.S)
    if not geom or not old:raise ValueError((ref,'pad geometry absent'))
    # Keep footprint-local orientation of original pad, do not accidentally
    # replace pin names / net names / CAD-assigned UUIDs.
    prev_angle=re.search(r'\(at [^)]*? ([-\d.]+)\)',old.group(0))
    new=geom.group(0)
    if prev_angle:
        new=re.sub(r'\(at ([^ )]+) ([^ )]+) ([^ )]+)\)',r'(at \1 \2 '+prev_angle.group(1)+')',new,count=1)
    return block[:old.start()]+new+block[old.end():]

raw_pcb=PCB.read_bytes(); raw_sch=SCH.read_bytes()
pcb=raw_pcb.decode('utf-8').replace('\r\n','\n')
sch=raw_sch.decode('utf-8').replace('\r\n','\n')
ra,rb=instance(pcb,'footprint','C1')
standard=pcb[ra:rb]
assert 'Capacitor_SMD:C_1206_3216Metric' in standard
native_geom=native_1206_geometry(standard)
pad_native={str(n):block_by_header(standard,f'(pad "{n}"') for n in (1,2)}
changes=[]
for ref,(newvalue,part) in TARGETS.items():
    a,b=instance(pcb,'footprint',ref)
    block=pcb[a:b]
    assert '(footprint "Capacitor_SMD:C_0603_1608Metric"' in block
    oldvalue=re.search(r'\(property "Value" "([^"]+)"',block).group(1)
    pad_nets=re.findall(r'\(net "([^"]+)"\)',block)
    pad_uuids=re.findall(r'\(pad "([12])".*?\(uuid "([^"]+)"\)',block,re.S)
    original_center=re.search(r'\(at [^)]*\)',block).group(0)
    block=sub1(block,'(footprint "Capacitor_SMD:C_0603_1608Metric"', '(footprint "Capacitor_SMD:C_1206_3216Metric"',ref)
    block=sub1(block, '(property "Value" "'+oldvalue+'"', '(property "Value" "'+newvalue+'"',ref)
    block=re.sub(r'\(descr "Capacitor SMD 0603[^"\n]*"\)',re.search(r'\(descr "[^"\n]*"\)',standard).group(0),block,count=1)
    # Remove 0603-only autogenerated property, no longer applicable.
    block=re.sub(r'\n\t\t\(property "KiLib_Generator".*?\n\t\t\)', '',block, count=1,flags=re.S)
    start=block.index('\n\t\t(fp_line')+1
    end=block.index('\n\t\t(pad "1"')+1
    geometry = re.sub(r'\(uuid "[^"]+"\)',lambda m:'(uuid "'+str(uuid.uuid5(uuid.NAMESPACE_URL,'VoiceMemory-1206:'+ref+':'+m.group(0)))+'")', native_geom)
    block=block[:start]+geometry+block[end:]
    for n in (1,2):
        oldpad=block_by_header(block,f'(pad "{n}"')
        newpad=replacing_pad_geom(oldpad,pad_native[str(n)],ref)
        block=sub1(block,oldpad,newpad,f'{ref}:pad{n}')
    block=block.replace('C_0603_1608Metric.step','C_1206_3216Metric.step')
    block=block.replace('"${KICAD10_3DMODEL_DIR}','"${KICAD10_3DMODEL_DIR}')
    assert re.findall(r'\(net "([^"]+)"\)',block)==pad_nets
    assert re.findall(r'\(pad "([12])".*?\(uuid "([^"]+)"\)',block,re.S)==pad_uuids
    assert original_center==re.search(r'\(at [^)]*\)',block).group(0)
    pcb=pcb[:a]+block+pcb[b:]

    a,b=instance(sch,'symbol',ref)
    unit=sch[a:b]
    old_sch=re.search(r'\(property "Value" "([^"]+)"',unit).group(1)
    unit=sub1(unit,'(property "Footprint" "Capacitor_SMD:C_0603_1608Metric"','(property "Footprint" "Capacitor_SMD:C_1206_3216Metric"',ref)
    unit=sub1(unit,'(property "Value" "'+old_sch+'"','(property "Value" "'+newvalue+'"',ref)
    sch=sch[:a]+unit+sch[b:]
    changes.append({'ref':ref,'previous_value':oldvalue,'new_value':newvalue,'footprint':'Capacitor_SMD:C_1206_3216Metric','part':part, 'nets':pad_nets, 'pad_uuids':pad_uuids})
assert len(changes)==11
for ref in ['C1','C3','C5','C6','C9','C12','C13','C18']:
 assert instance(pcb,'footprint',ref) and instance(sch,'symbol',ref)
PCB.write_bytes(pcb.replace('\n','\r\n').encode('utf-8') if b'\r\n' in raw_pcb else pcb.encode('utf-8'))
SCH.write_bytes(sch.replace('\n','\r\n').encode('utf-8') if b'\r\n' in raw_sch else sch.encode('utf-8'))
report={'date':'2026-11-10','basis':'v1-cap-sourcing-2026-11-10', 'minimum_smd':'0805 (2012)',
 'change_count':len(changes),'changes':changes,'source_of_native_footprint':'C1 official KiCad C_1206_3216Metric geometry copied in full; no custom cache',
 'limitations':['KiCad10 executable not installed: official ERC/DRC not executed','PCB retained original component XY and tracks/vias; must run DRC, re-layout if clashes','Zone refill not executed; original GND zones need refill','Sengoku stock quantity not directly guaranteed; recheck at purchase']}
q=BASE/'hardware/reports/CAP_MIN_0805_2026-11-10.json'
q.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'changed':len(changes), 'refs':sorted(TARGETS), 'pcb_sha256':hashlib.sha256(PCB.read_bytes()).hexdigest(), 'sch_sha256':hashlib.sha256(SCH.read_bytes()).hexdigest()},indent=2))
